"""Regenerate luanma/freq.py from open data. Run once; output is committed.

Sources (downloaded into ./build_data):
  jieba dict.txt   (MIT)        https://github.com/fxsjy/jieba
  OpenCC STCharacters / STPhrases (Apache-2.0)  https://github.com/BYVoid/OpenCC
"""
import collections, pathlib, sys

SRC = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "build_data")
OUT = pathlib.Path(__file__).resolve().parents[1] / "luanma" / "freq.py"
N_CHARS, N_PAIRS = 4000, 20000

is_han = lambda c: 0x4E00 <= ord(c) <= 0x9FFF

chars, pairs = collections.Counter(), collections.Counter()
for line in (SRC / "dict.txt").read_text("utf-8").splitlines():
    p = line.split()
    if len(p) < 2:
        continue
    w, f = p[0], int(p[1])
    if not all(is_han(c) for c in w):
        continue
    for c in w:
        chars[c] += f
    for a, b in zip(w, w[1:]):
        pairs[a + b] += f

s2t = {}
for line in (SRC / "STCharacters.txt").read_text("utf-8").splitlines():
    if line.startswith("#") or "\t" not in line:
        continue
    k, v = line.split("\t")
    s2t[k] = v.split()[0]
phr = {}
for line in (SRC / "STPhrases.txt").read_text("utf-8").splitlines():
    if "\t" in line and not line.startswith("#"):
        k, v = line.split("\t")
        if len(k) == 2:
            phr[k] = v.split()[0]

top_chars = [c for c, _ in chars.most_common(N_CHARS)]
top_pairs = [p for p, _ in pairs.most_common(N_PAIRS)]
trad_chars = [s2t.get(c, c) for c in top_chars]
trad_pairs = [phr.get(p) or "".join(s2t.get(c, c) for c in p) for p in top_pairs]

allpairs = list(dict.fromkeys(top_pairs + trad_pairs))

OUT.write_text(
    '"""Generated by tools/build_tables.py from jieba (MIT) and OpenCC (Apache-2.0). Do not edit."""\n'
    f"TOP = {''.join(top_chars)!r}\n"
    f"TOP_TRAD = {''.join(trad_chars)!r}\n"
    "RANK = {}\n"
    "for _i, (_s, _t) in enumerate(zip(TOP, TOP_TRAD)):\n"
    "    RANK.setdefault(_s, _i)\n"
    "    RANK.setdefault(_t, _i)\n"
    f"WORDS = set({' '.join(allpairs)!r}.split())\n",
    encoding="utf-8",
)
print(f"wrote {OUT}: {len(top_chars)} chars, {len(allpairs)} pairs, {OUT.stat().st_size//1024} KB")
